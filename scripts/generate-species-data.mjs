// Generate the small browser species catalogue from the pinned FireRed source.
// Run after scripts/get-pokefirered.sh whenever that source or the team rules change.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = (path) => readFileSync(resolve(root, 'pokefirered', path), 'utf8');
const constants = read('include/constants/species.h');
const ids = new Map([...constants.matchAll(/^#define SPECIES_(\w+)\s+(\d+)\b/gm)]
  .map((m) => [m[1], Number(m[2])]));
const names = new Map([...read('src/data/text/species_names.h').matchAll(/\[SPECIES_(\w+)\]\s*=\s*_\("([^"]+)"\)/g)]
  .map((m) => [m[1], m[2]]));
const source = read('src/dailyred_team.c');
const legendary = new Set([...source.match(/sLegendaries\[\] =\s*\{([^}]*)\}/)[1].matchAll(/SPECIES_(\w+)/g)]
  .map((m) => m[1]));
const statFields = ['baseHP', 'baseAttack', 'baseDefense', 'baseSpeed', 'baseSpAttack', 'baseSpDefense'];
const rows = [];
for (const chunk of read('src/data/pokemon/species_info.h').split('[SPECIES_').slice(1)) {
  const key = chunk.split(']')[0];
  const id = ids.get(key);
  if (!id || id >= 412 || (id >= ids.get('OLD_UNOWN_B') && id <= ids.get('OLD_UNOWN_Z')) || rows.some((row) => row[0] === id)) continue;
  const stats = statFields.map((field) => chunk.match(new RegExp(`\\.${field}\\s*=\\s*(\\d+)`))?.[1]);
  if (stats.some((value) => value === undefined) || !names.has(key)) continue;
  rows.push([id, names.get(key), stats.reduce((sum, value) => sum + Number(value), 0), legendary.has(key) ? 1 : 0]);
}
rows.sort((a, b) => a[0] - b[0]);
if (rows.length !== 386 || rows.some((row) => !Number.isInteger(row[2]) || row[2] <= 0)) {
  throw new Error(`Expected 386 Gen 1–3 species; found ${rows.length}`);
}
const output = `// Generated by scripts/generate-species-data.mjs from the pinned FireRed source.\n`
  + `// Each row is [species ID, displayed name, base stat total, legendary flag].\n`
  + `export const SPECIES = ${JSON.stringify(rows)};\n`;
const target = resolve(root, 'web/species-data.js');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('web/species-data.js is out of date');
} else {
  writeFileSync(target, output);
}
